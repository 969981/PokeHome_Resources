#!/usr/bin/env python3
"""Split >90 MiB Apktool project members for Git; restore before apktool build."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import tempfile

MANIFEST = '.large-file-shards.json'
PARTS_DIR = '.shards'
LIMIT = 90 * 1024 * 1024
PART_SIZE = 48 * 1024 * 1024


def sha256_file(path):
    h = hashlib.sha256()
    with path.open('rb') as stream:
        for chunk in iter(lambda: stream.read(2 * 1024 * 1024), b''):
            h.update(chunk)
    return h.hexdigest()


def checked_path(root, rel):
    target = (root / rel).resolve()
    if not target.is_relative_to(root.resolve()):
        raise ValueError('Unsafe relative path: ' + str(rel))
    return target


def split(root):
    entries = []
    for path in sorted(root.rglob('*')):
        if not path.is_file() or PARTS_DIR in path.relative_to(root).parts:
            continue
        if path.stat().st_size <= LIMIT:
            continue
        rel = path.relative_to(root).as_posix()
        identifier = hashlib.sha256(rel.encode('utf-8')).hexdigest()[:20]
        parts = []
        with path.open('rb') as inp:
            index = 0
            while block := inp.read(PART_SIZE):
                part_rel = f'{PARTS_DIR}/{identifier}/{index:04d}.part'
                part = checked_path(root, part_rel)
                part.parent.mkdir(parents=True, exist_ok=True)
                part.write_bytes(block)
                parts.append({'path': part_rel, 'size': len(block),
                              'sha256': hashlib.sha256(block).hexdigest()})
                index += 1
        entries.append({'path': rel, 'size': path.stat().st_size,
                        'sha256': sha256_file(path), 'parts': parts})
        path.unlink()
    (root / MANIFEST).write_text(json.dumps({'version': 1, 'entries': entries}, indent=2) + '\n', encoding='utf-8')
    (root / '.gitignore').write_text(
        '# Generated by shard_large.py: restored large binary members only\n' +
        ''.join('/' + entry['path'] + '\n' for entry in entries), encoding='utf-8')
    return entries


def verify_record(root, entry):
    dest = checked_path(root, entry['path'])
    if not dest.exists() or dest.stat().st_size != entry['size'] or sha256_file(dest) != entry['sha256']:
        raise ValueError('Missing/mismatched restored file: ' + entry['path'])
    return dest


def restore(root, entries):
    for entry in entries:
        dest = checked_path(root, entry['path'])
        if dest.exists():
            verify_record(root, entry)
            continue
        dest.parent.mkdir(parents=True, exist_ok=True)
        fd, tempname = tempfile.mkstemp(prefix='.restore-', dir=str(dest.parent))
        try:
            with os.fdopen(fd, 'wb') as out:
                for info in entry['parts']:
                    part = checked_path(root, info['path'])
                    if part.stat().st_size != info['size'] or sha256_file(part) != info['sha256']:
                        raise ValueError('Corrupt shard: ' + info['path'])
                    with part.open('rb') as inp:
                        for block in iter(lambda: inp.read(2 * 1024 * 1024), b''):
                            out.write(block)
            os.replace(tempname, dest)
            verify_record(root, entry)
        finally:
            if os.path.exists(tempname):
                os.unlink(tempname)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=['split', 'restore', 'clean', 'check'])
    parser.add_argument('--root', type=Path, required=True)
    args = parser.parse_args()
    root = args.root.resolve()
    if not (root / 'apktool.yml').exists():
        parser.error('Expected decoded Apktool project with apktool.yml')
    if args.action == 'split':
        entries = split(root)
    else:
        entries = json.loads((root / MANIFEST).read_text(encoding='utf-8'))['entries']
        if args.action == 'restore':
            restore(root, entries)
        elif args.action == 'clean':
            for entry in entries:
                dest = checked_path(root, entry['path'])
                if dest.exists():
                    verify_record(root, entry)
                    dest.unlink()
        elif args.action == 'check':
            for entry in entries:
                for info in entry['parts']:
                    part = checked_path(root, info['path'])
                    if part.stat().st_size != info['size'] or sha256_file(part) != info['sha256']:
                        raise ValueError('Corrupt shard: ' + info['path'])
    print(f'{args.action}: {len(entries)} large files; root={root}')


if __name__ == '__main__':
    main()
